import random
import bptree as bp


def test_search_on_empty_and_single():
    t = bp.BPlusTree(order=4)
    assert t.search(5) is None
    t.insert(5, "five")
    assert t.search(5) == "five"
    assert t.search(6) is None


def test_sequential_insert_and_search():
    t = bp.BPlusTree(order=4)
    for i in range(1, 51):
        t.insert(i, i * 10)
    for i in range(1, 51):
        assert t.search(i) == i * 10
    assert t.height() >= 2          # must have split beyond a single leaf
    t.check_invariants()


def test_update_existing_key_no_duplicate():
    t = bp.BPlusTree(order=5)
    t.insert(3, "a")
    t.insert(3, "b")
    assert t.search(3) == "b"
    t.check_invariants()


def test_random_insert_keeps_invariants():
    t = bp.BPlusTree(order=4)
    keys = list(range(200))
    random.Random(303).shuffle(keys)
    ref = {}
    for k in keys:
        t.insert(k, k)
        ref[k] = k
        t.check_invariants()        # balanced & well-occupied after every insert
    for k in range(200):
        assert t.search(k) == ref[k]


def test_range_scan_basic():
    t = bp.BPlusTree(order=4)
    for i in range(100):
        t.insert(i, i)
    assert list(t.range(10, 20)) == [(i, i) for i in range(10, 21)]
    assert list(t.range(-5, 3)) == [(i, i) for i in range(0, 4)]
    assert list(t.range(97, 500)) == [(i, i) for i in range(97, 100)]


def test_range_scan_on_shuffled_sparse_keys():
    t = bp.BPlusTree(order=6)
    keys = list(range(0, 300, 3))
    random.Random(7).shuffle(keys)
    for k in keys:
        t.insert(k, str(k))
    got = [k for k, _ in t.range(30, 90)]
    assert got == [k for k in range(30, 91) if k % 3 == 0]


def test_large_tree_stays_shallow():
    t = bp.BPlusTree(order=50)
    for i in range(5000):
        t.insert(i, i)
    t.check_invariants()
    assert t.height() <= 4          # high fanout => shallow tree
    assert t.search(4999) == 4999
    assert list(t.range(4990, 5100)) == [(i, i) for i in range(4990, 5000)]