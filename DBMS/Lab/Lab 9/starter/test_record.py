import struct

import pytest

import record as r

STU = r.STUDENT
ZHANG = (128, "Zhang", "Comp. Sci.", 102)


def test_exact_bytes_for_known_row():
    # layout: num_fields(2) bitmap(1) offsets(2x2) id(4) tot_cred(2) | "Zhang" "Comp. Sci."
    got = r.encode(STU, ZHANG)
    want = (struct.pack("<H", 4) + bytes([0]) + struct.pack("<HH", 18, 28)
            + struct.pack("<i", 128) + struct.pack("<h", 102) + b"Zhang" + b"Comp. Sci.")
    assert got == want
    assert len(got) == 28


def test_roundtrip_simple():
    assert r.decode(STU, r.encode(STU, ZHANG)) == ZHANG


def test_null_varchar_takes_no_bytes():
    rec = r.encode(STU, (70557, "Snow", None, 0))
    assert len(rec) == 13 + len("Snow")
    assert rec[2] == 0b0100                      # bit 2 = dept_name is NULL
    assert r.decode(STU, rec) == (70557, "Snow", None, 0)


def test_null_fixed_keeps_its_slot():
    a = r.encode(STU, (1, "A", "B", 5))
    b = r.encode(STU, (1, "A", "B", None))
    assert len(a) == len(b)                      # fixed slot is reserved
    assert b[2] == 0b1000                        # bit 3 = tot_cred NULL
    assert r.decode(STU, b) == (1, "A", "B", None)


def test_all_null_and_empty_strings_are_different():
    rec_null = r.encode(STU, (None, None, None, None))
    rec_empty = r.encode(STU, (0, "", "", 0))
    assert r.decode(STU, rec_null) == (None, None, None, None)
    assert r.decode(STU, rec_empty) == (0, "", "", 0)
    assert rec_null != rec_empty


def test_get_field_is_direct(monkeypatch):
    rec = r.encode(STU, ZHANG)
    monkeypatch.setattr(r, "decode", lambda *a, **k: (_ for _ in ()).throw(AssertionError("get_field must not call decode")))
    assert r.get_field(STU, rec, 0) == 128
    assert r.get_field(STU, rec, 1) == "Zhang"
    assert r.get_field(STU, rec, 2) == "Comp. Sci."
    assert r.get_field(STU, rec, 3) == 102
    with pytest.raises(IndexError):
        r.get_field(STU, rec, 4)


def test_second_varchar_located_via_offsets():
    schema = [("a", "VARCHAR"), ("b", "VARCHAR"), ("c", "VARCHAR")]
    rec = r.encode(schema, ("first", None, "third"))
    assert r.get_field(schema, rec, 1) is None
    assert r.get_field(schema, rec, 2) == "third"


def test_mixed_types_and_unicode():
    schema = [("code", ("CHAR", 6)), ("score", "FLOAT"), ("note", "VARCHAR"), ("n", "SMALLINT"), ("k", "INT")]
    row = ("CS303", 9.25, "भिलाई — Bhilai", -7, -2_000_000_000)
    assert r.decode(schema, r.encode(schema, row)) == row


def test_many_fields_need_two_bitmap_bytes():
    schema = [(f"f{i}", "SMALLINT") for i in range(10)]
    vals = tuple(None if i in (0, 9) else i for i in range(10))
    rec = r.encode(schema, vals)
    assert rec[2] == 0b00000001 and rec[3] == 0b00000010
    assert r.decode(schema, rec) == vals


def test_wrong_arity_and_char_overflow():
    with pytest.raises(ValueError):
        r.encode(STU, (1, "x", "y"))
    with pytest.raises(ValueError):
        r.encode([("c", ("CHAR", 3))], ("toolong",))
    with pytest.raises(ValueError):
        r.decode([("x", "INT")], r.encode(STU, ZHANG))
