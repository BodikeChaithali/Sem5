import math
import random

import fileorg as fo


def recs(keys):
    return [(k, f"v{k}") for k in keys]


def build(cls, keys, **kw):
    d = fo.Disk()
    f = cls(d, **kw)
    f.load(recs(keys))
    d.reset_counters()
    return d, f


# ---------------- correctness ----------------

def test_sorted_lookup_correct():
    keys = list(range(0, 400, 2))
    _, f = build(fo.SortedFile, keys, cap=4)
    for k in keys:
        assert f.lookup(k) == f"v{k}"
    for k in (-5, 1, 199, 401, 10_000):
        assert f.lookup(k) is None


def test_hashed_lookup_correct():
    keys = random.Random(7).sample(range(10_000), 300)
    _, f = build(fo.HashedFile, keys, nbuckets=16, cap=4)
    for k in keys:
        assert f.lookup(k) == f"v{k}"
    assert f.lookup(10_001) is None


def test_range_correct_for_all_three():
    keys = random.Random(11).sample(range(1000), 250)
    want = sorted((k, f"v{k}") for k in keys if 300 <= k <= 420)
    for cls, kw in ((fo.HeapFile, {}), (fo.SortedFile, {}), (fo.HashedFile, {"nbuckets": 16})):
        _, f = build(cls, keys, cap=4, **kw)
        assert f.range(300, 420) == want, cls.__name__


def test_random_inserts_match_dict():
    rng = random.Random(303)
    for cls, kw in ((fo.SortedFile, {}), (fo.HashedFile, {"nbuckets": 8})):
        d = fo.Disk()
        f = cls(d, cap=4, **kw)
        f.load(recs(range(0, 200, 5)))
        ref = {k: f"v{k}" for k in range(0, 200, 5)}
        for _ in range(150):
            k = rng.randrange(1000)
            if k not in ref:
                f.insert(k, f"v{k}")
                ref[k] = f"v{k}"
        for k, v in ref.items():
            assert f.lookup(k) == v, (cls.__name__, k)
        assert f.range(0, 999) == sorted(ref.items())


# ---------------- I/O behaviour (Lecture 21 cost table) ----------------

def test_sorted_lookup_is_logarithmic():
    d, f = build(fo.SortedFile, range(1024), cap=4)        # B = 256 primary pages
    B = f.num_pages()
    worst = 0
    for k in random.Random(1).sample(range(1024), 60):
        d.reset_counters()
        assert f.lookup(k) == f"v{k}"
        worst = max(worst, d.reads)
    assert worst <= math.ceil(math.log2(B)) + 2, f"{worst} reads for B={B}"


def test_hashed_lookup_is_one_read_without_overflow():
    d, f = build(fo.HashedFile, range(64), nbuckets=16, cap=4)  # exactly 4 per bucket
    assert f.num_pages() == 16
    for k in range(64):
        d.reset_counters()
        f.lookup(k)
        assert d.reads == 1


def test_hashed_overflow_chain_grows_and_costs_reads():
    d = fo.Disk()
    f = fo.HashedFile(d, nbuckets=4, cap=2)
    colliders = [4 * i for i in range(7)]                  # all hash to bucket 0
    for k in colliders:
        f.insert(k, f"v{k}")
    assert f.num_pages() == 4 + 3                          # 7 records, 2 per page -> 3 overflow pages
    d.reset_counters()
    assert f.lookup(24) == "v24"                           # last record: 4th page of the chain
    assert d.reads == 4
    d.reset_counters()
    assert f.lookup(4 * 99) is None                        # miss must walk the whole chain
    assert d.reads == 4


def test_sorted_range_reads_only_needed_pages():
    d, f = build(fo.SortedFile, range(1024), cap=4)        # B = 256
    d.reset_counters()
    got = f.range(500, 531)                                # spans 8 pages
    assert [k for k, _ in got] == list(range(500, 532))
    assert d.reads <= math.ceil(math.log2(256)) + 2 + 8 + 1


def test_hashed_range_reads_every_page():
    d, f = build(fo.HashedFile, range(200), nbuckets=10, cap=4)
    total = f.num_pages()
    d.reset_counters()
    f.range(50, 52)                                        # tiny range, still a full scan
    assert d.reads == total


def test_sorted_overflow_insert_is_found():
    d, f = build(fo.SortedFile, range(0, 80, 10), cap=4)   # pages [0,10,20,30] [40,50,60,70]
    for k in (11, 12, 13, 14, 15):                         # all belong to the full first page
        f.insert(k, f"v{k}")
    assert f.num_pages() == 2                              # primary pages unchanged
    assert d.pages[f.pids[0]]["next"] is not None          # an overflow chain appeared
    for k in (11, 12, 13, 14, 15, 30, 40):
        assert f.lookup(k) == f"v{k}"
    assert [k for k, _ in f.range(12, 41)] == [12, 13, 14, 15, 20, 30, 40]


def test_empty_files():
    for cls, kw in ((fo.SortedFile, {}), (fo.HashedFile, {"nbuckets": 4})):
        d = fo.Disk()
        f = cls(d, cap=4, **kw)
        assert f.lookup(1) is None
        assert f.range(0, 10) == []
